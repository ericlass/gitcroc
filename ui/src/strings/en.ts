// The English text of the UI (D15), by area. A text with values is a
// function of them, which also holds the plural rule. Components import
// this; there is no language switch and no translation library, since
// translations are LATER (section 2). Text the core sends (errors, skip and
// block reasons, git's output) is shown as it arrives and is not here.

const plural = (count: number, one: string, many: string) => `${count} ${count === 1 ? one : many}`;

/** A step of an operation, such as a rebase's `3 of 7`. */
interface Step {
  current: number;
  total: number;
}

/** `: merging topic into main`, or nothing when the core read nothing of what is applied. */
const applyingWhat = (verb: string, joint: string, applying: string | null, onto: string | null) =>
  applying === null ? "" : `: ${verb} ${applying}${onto === null ? "" : ` ${joint} ${onto}`}`;

const unmergedCount = (paths: number) => (paths === 1 ? "1 path is unmerged" : `${paths} paths are unmerged`);

